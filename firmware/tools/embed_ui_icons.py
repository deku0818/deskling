"""Copy the web's pixel icon masks into LVGL A8 images."""
import ast
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = (root / "web/index.html").read_text().split("const iconPixels={", 1)[1].split("\n};", 1)[0]
icons = {name: ast.literal_eval(rows) for name, rows in re.findall(r"(\w+):(\[[^\n]+\])", source)}
output = ["// Pixel masks shared with web/index.html. Generated by tools/embed_ui_icons.py.", "#pragma once"]
for name, rows in icons.items():
    pixels = [0] * 576
    for y, row in enumerate(rows):
        for x, value in enumerate(row):
            if value == "1":
                for yy in range((y + 1) * 2, (y + 2) * 2):
                    for xx in range((x + 1) * 2, (x + 2) * 2):
                        pixels[yy * 24 + xx] = 255
    output.append("static const uint8_t icon_" + name + "_pixels[] = {" + ",".join(map(str, pixels)) + "};")
    output.append(f"static const lv_image_dsc_t icon_{name} = {{.header = {{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w=24,.h=24,.stride=24}},.data_size=576,.data=icon_{name}_pixels}};")
(root / "firmware/main/ui_icons.h").write_text("\n".join(output) + "\n")
