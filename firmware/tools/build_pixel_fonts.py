"""Build the device's Fusion Pixel fonts. Needs fonttools[woff] and lv_font_conv 1.5.3."""
import argparse
import hashlib
from io import BytesIO
from pathlib import Path
import re
import subprocess
import tempfile
import urllib.request
import zipfile
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
URL = "https://github.com/TakWolf/fusion-pixel-font/releases/download/2026.09.25/fusion-pixel-font-12px-monospaced-otf.woff2-v2026.09.25.zip"
SHA256 = "d55feb57eed56183d0e0b09ab04deea0cbbfece0282ba0e840e07c7feac5f812"
FALLBACK_URL = "https://raw.githubusercontent.com/notofonts/noto-cjk/main/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf"
FALLBACK_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
RANGES = "0x20-0x7E,0xA0-0xFF,0x2000-0x206F,0x3000-0x30FF,0x3400-0x9FFF,0xFF00-0xFFEF"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--archive")
parser.add_argument("--fallback-font", help="Optional local Noto Sans CJK SC Regular OTF")
parser.add_argument("--converter", required=True)
args = parser.parse_args()
converter = str(Path(args.converter).resolve())
if args.archive:
    data = Path(args.archive).read_bytes()
else:
    with urllib.request.urlopen(URL, timeout=60) as response:
        data = response.read()
if hashlib.sha256(data).hexdigest() != SHA256:
    raise SystemExit("Font archive hash mismatch; review the release before updating.")
archive = zipfile.ZipFile(BytesIO(data))
font = TTFont(BytesIO(archive.read("fusion-pixel-12px-monospaced-zh_hans.otf.woff2")))
if args.fallback_font:
    fallback_data = Path(args.fallback_font).read_bytes()
else:
    with urllib.request.urlopen(FALLBACK_URL, timeout=60) as response:
        fallback_data = response.read()
if hashlib.sha256(fallback_data).hexdigest() != FALLBACK_SHA256:
    raise SystemExit("Fallback font hash mismatch; review the source before updating.")
pixel_cmap = font.getBestCmap()
fallback_cmap = TTFont(BytesIO(fallback_data)).getBestCmap()
missing = "".join(chr(c) for c in range(0x4e00, 0xa000) if c not in pixel_cmap and c in fallback_cmap)
text = (ROOT / "web/index.html").read_text() + (ROOT / "firmware/main/ui.c").read_text() + (ROOT / "firmware/main/network.c").read_text() + (ROOT / "firmware/main/provision_config.c").read_text()
with tempfile.TemporaryDirectory(prefix="deskling-pixel-") as directory:
    folder = Path(directory)
    font.flavor = None
    font.save(folder / "fusion-pixel.otf")
    (folder / "noto-cjk.otf").write_bytes(fallback_data)
    for size in [12, 20, 24, 28]:
        name = f"deskling_pixel_{size}"
        if size == 24:
            selection = ["--range", RANGES, "--font", "noto-cjk.otf", "--autohint-off", "--symbols", missing]
        else:
            symbols = "".join(sorted(set(text))) if size == 12 else ("0123456789%-." if size == 28 else "".join(chr(c) for c in range(32, 127)))
            selection = ["--symbols", symbols]
        subprocess.run([
            converter, "--font", "fusion-pixel.otf", "--autohint-off", *selection,
            "--size", str(size), "--bpp", "1", "--no-kerning", "--format", "lvgl",
            "--lv-include", "lvgl.h", "--lv-font-name", name, "-o", name + ".c",
        ], cwd=folder, check=True)
        output = (folder / (name + ".c")).read_text()
        # Match CSS line boxes using the font's hhea 1000/-200, unitsPerEm 1200.
        # Rare combining marks otherwise inflate lv_font_conv's computed line height.
        output = re.sub(r"    \.line_height = \d+,.*", f"    .line_height = {size}, /* Match the web CSS em box. */", output)
        output = re.sub(r"    \.base_line = \d+,.*", f"    .base_line = {round(size / 6)},", output)
        output = re.sub(r"\A/\*.*?\*/", "/* Fusion Pixel Font 2026.09.25 with Noto CJK fallback; generated by tools/build_pixel_fonts.py. */", output, count=1, flags=re.S)
        (ROOT / "firmware/main/fonts" / (name + ".c")).write_text(output)
        print("Generated", name)
